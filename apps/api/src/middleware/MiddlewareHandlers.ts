import { toErrorResponse } from '@/errors/errorResponse';
import { authenticateAccess, errorBody } from '@rexezuge/http';
import { ServiceError } from '@rexezuge/errors';
import { Context, Next } from 'hono';
import type { ContentfulStatusCode } from 'hono/utils/http-status';
import { createRequestScope, Tokens } from '@mail-meow/backend-services/composition';

type UserContext = Context<{ Bindings: Env; Variables: { AuthenticatedUserEmailAddress: string; AuthenticatedUserId: string } }>;

/**
 * The bindings `authenticateAccess` reads.
 *
 * `ACCESS` is the one Cloudflare provisions for a Worker sitting behind an Access
 * application and `wrangler types` therefore never emits — declared here so its
 * absence is a *type* fact rather than a cast at the call site.
 * `authenticateAccess` treats an absent binding as "401", never as "allow", so
 * that is a supported state rather than a gap to be filled in.
 *
 * The three settings are restated rather than intersected with the generated
 * `Env`. `Env` is regenerated by `wrangler types` and is a `type` alias, not an
 * interface, so an intersection with it resolves to "the alias" and every
 * property on it reports as missing to a type-aware linter — which is a tooling
 * artefact that would otherwise need a disable comment to live with forever.
 */
interface AccessEnv {
  ACCESS?: {
    getIdentity(): Promise<{ email?: string | null; emailVerified?: boolean | null; email_verified?: boolean | null } | undefined>;
  };
  DEV_AUTH_EMAIL?: string;
  TEAM_DOMAIN?: string;
  POLICY_AUD?: string;
}

/**
 * Authenticate the request and resolve the address to an account.
 *
 * The account id is what identifies the caller for anything id-keyed
 * (connected applications, task-run visibility), so it is published on the
 * context next to the address. The address stays because it is the only thing
 * Cloudflare Access asserts, and because a database that has not run migration
 * 0011 has no id to publish.
 */
class MiddlewareHandlers {
  public static userAuthentication() {
    return async (c: UserContext, next: Next): Promise<Response | void> => {
      const scope = createRequestScope(c.env);
      try {
        const userEmail: string = await MiddlewareHandlers.authenticate(c);
        // Resolve-then-create, so an address that already identifies an account
        // signs into that account rather than forking a second one.
        const account = await scope.get(Tokens.UserService).upsertUser(userEmail);
        c.set('AuthenticatedUserEmailAddress', userEmail);
        // Empty on a pre-0011 database; the DAOs then key on the address alone.
        c.set('AuthenticatedUserId', account?.id ?? '');
        await next();
      } catch (error: unknown) {
        // A 4xx at the auth boundary is answered here with the family envelope.
        // Anything 5xx or untyped is rethrown: this middleware has no envelope of
        // its own to fall back on, and the entrypoint's catch-all is what logs
        // them. That split is the one thing `errorResponse.ts` does for us and
        // `authenticateAccess` does not.
        if (error instanceof ServiceError && error.status < 500) {
          console.warn(`Responding with ${error.type} during authentication`);
          return c.json(errorBody(error), error.status as ContentfulStatusCode);
        }
        // `toErrorResponse` still runs, because it is what produces the redacted
        // log line for the rethrown case. The throw is what actually happens.
        const response = toErrorResponse(error);
        if (response.logDetail !== null) {
          console.error('Caught an untyped error during authentication:', response.logDetail);
        }
        throw error;
      }
    };
  }

  /**
   * Identify the caller as a Cloudflare Access user.
   *
   * `@rexezuge/http`'s `authenticateAccess`, which replaces a local
   * `EmailValidationUtil`. Three things change, each worth having.
   *
   * **The dev bypass is an explicit allow-list, not the mere presence of a var.**
   * Before, setting `DEV_AUTH_EMAIL` disabled Access for that environment
   * unconditionally — which is precisely the shape of a mistake that reaches
   * production, where every request becomes one operator's mailbox. The
   * affordance is unchanged for local development; the decision is now one named
   * line rather than a side effect inside the resolver.
   *
   * **A bypass address is validated and lowercased.** The old path returned
   * `DEV_AUTH_EMAIL` verbatim, so a malformed value flowed straight into
   * `upsertUser` and tried to register a garbage account — and it skipped the
   * normalisation every other address in the system is stored under.
   *
   * **Every JWT failure collapses to one message.** Before, the verifier's own
   * text was forwarded — "signature verification failed" versus "expired" tells
   * an unauthenticated caller precisely which part of a forged token they got
   * right.
   */
  private static authenticate(c: UserContext): Promise<string> {
    const env = c.env as AccessEnv;
    const devAuthEmail: string | undefined = env.DEV_AUTH_EMAIL;
    return authenticateAccess(c.req.raw, env.ACCESS, {
      bypassAllowed: Boolean(devAuthEmail),
      devAuthEmail,
      teamDomain: env.TEAM_DOMAIN,
      policyAud: env.POLICY_AUD,
    });
  }
}

export { MiddlewareHandlers };
export type { AccessEnv };
